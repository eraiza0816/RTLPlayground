/* RFC 7539 section 2.5.2: Poly1305 test vector */
static void test_poly1305(void)
{
	static uint8_t key[32], msg[34], mac[16];
	static const uint8_t key_data[32] = {
		0x85,0xd6,0xbe,0x78,0x57,0x55,0x6d,0x33,0x7f,0x44,0x52,0xfe,0x42,0xd5,0x06,0xa8,
		0x01,0x03,0x80,0x8a,0xfb,0x0d,0xb2,0xfd,0x4a,0xbf,0xf6,0xaf,0x41,0x49,0xf5,0x1b }; /* RFC: ...fb0db2fd... */
	static const uint8_t msg_hex[34] = {
		0x43,0x72,0x79,0x70,0x74,0x6f,0x67,0x72,0x61,0x70,0x68,0x69,0x63,0x20,0x46,0x6f,
		0x72,0x75,0x6d,0x20,0x52,0x65,0x73,0x65,0x61,0x72,0x63,0x68,0x20,0x47,0x72,0x6f,
		0x75,0x70 };
	static const uint8_t expect[16] = {
		0xa8,0x06,0x1d,0xc1,0x30,0x51,0x36,0xc6,0xc2,0x2b,0x8b,0xaf,0x0c,0x01,0x27,0xa9 };
	struct poly1305_t p;

	memcpy(key, key_data, 32);
	memcpy(msg, msg_hex, 34);

	poly1305_init(&p, key);
	poly1305_update(&p, msg, 34);
	poly1305_finish(&p, mac);

	check("poly1305 RFC7539 2.5.2", memcmp(mac, expect, 16) == 0);
}

int main(void)
{
	test_chacha20();
	test_poly1305();
	/* RFC 8439 section 2.8.2 (encrypt/decrypt/tamper) — the firmware's own
	 * self-test with the "Ladies and Gentlemen..." vector. */
	aead_test();

	if (failures) {
		printf("aead_test_host: %d FAILURE(S)\n", failures);
		return 1;
	}
	printf("aead_test_host: all tests passed\n");
	return 0;
}
