/*
 * aead_test — host-side RFC 8439 test vector verification for the
 * firmware's ChaCha20-Poly1305 AEAD (crypto/aead.c, chacha20.c, poly1305.c).
 *
 * The same sources are compiled with the host shim (rtl837x_common.h) so the
 * firmware implementation itself is validated against the RFC vectors that
 * the Go tooling (tools/rtlpctl/aead_test.go) already checks.
 *
 * Build (via tools/Makefile): gcc -O2 -Wall -Wno-unknown-pragmas -I.
 *   -include rtl837x_common.h aead_test.c ../crypto/aead.c
 *   ../crypto/chacha20.c ../crypto/poly1305.c -o output/aead_test
 */

#include <stdio.h>
#include <string.h>
#include <stdint.h>

/* Stubs for the firmware helpers declared in tools/rtl837x_common.h.
 * print_string/print_byte are used by crypto/aead.c (aead_test). */
void print_string(const char *s) { fputs(s, stdout); }
void print_byte(unsigned char b) { printf("%02x", b); }
void memcpyc(void *dst, const void *src, unsigned int len) { memcpy(dst, src, len); }

#include "../crypto/aead.h"
#include "../crypto/chacha.h"
#include "../crypto/poly1305.h"

static int failures = 0;

static void check(const char *name, int ok)
{
	if (ok)
		printf("PASS %s\n", name);
	else {
		printf("FAIL %s\n", name);
		failures++;
	}
}

